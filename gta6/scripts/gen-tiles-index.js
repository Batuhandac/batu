#!/usr/bin/env node
/* Generates content/tiles.ts with static require() calls for every bundled map tile. */
const fs = require('fs');
const path = require('path');
const root = path.join(__dirname, '..');
const sets = ['yanis', 'dupzor'];
let out = '/* AUTO-GENERATED by scripts/gen-tiles-index.js. Do not edit. */\n/* eslint-disable */\n';
for (const set of sets) {
  const files = fs.readdirSync(path.join(root, 'assets', 'tiles', set)).filter((f) => f.endsWith('.jpg')).sort();
  out += `export const ${set.toUpperCase()}_TILES: Record<string, number> = {\n`;
  for (const f of files) out += `  '${f.replace('.jpg', '')}': require('../assets/tiles/${set}/${f}'),\n`;
  out += '};\n';
}
fs.writeFileSync(path.join(root, 'content', 'tiles.ts'), out);
console.log('content/tiles.ts written');
